test('cools the other House, lets players spend a bonus card, and enforces two skips', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'New game' }).click()
  await page.getByRole('button', { name: 'Pass & play' }).click()
  await page.getByRole('button', { name: 'Add House' }).click()
  await page.getByRole('button', { name: 'Start game' }).click()

  await place(page, 1).click()
  const houses = site(page, 'House')
  await expect(houses.first()).toContainText('Next can finish')
  await houses.first().click()
  await place(page, 1).click()
  await expect(houses.first()).toBeEnabled()
  await expect(houses.first()).toContainText('Finish now')
  await expect(houses.last()).toBeDisabled()
  await expect(houses.last()).toContainText('Cooldown · 1 turn')
  await expect(page.getByRole('button', { name: /^Map site 1, House/ })).toBeEnabled()
  await expect(page.getByRole('button', { name: /^Map site 2, House/ })).toBeDisabled()

  const double = page.getByRole('button', { name: /^Double Load/ })
  const cart = page.getByRole('button', { name: /^Brick Cart/ })
  await double.click()
  await expect(double).toHaveAttribute('aria-pressed', 'true')
  await place(page, 4).click()
  await double.click()
  await expect(place(page, 4)).toHaveCount(0)
  await cart.click()
  await place(page, 4).click()
  await site(page, 'Workshop').click()
  await expect(page.locator('.activity')).toContainText('Used Brick Cart.')
  await expect(page.locator('.score.player-1')).toContainText('10 / 12 bricks')
  await expect(page.locator('.score.player-1')).toContainText('2 skips · 1 card')
  await expect(cart).toBeEnabled()

  await place(page, 1).click()
  await expect(houses.first()).toBeEnabled()
  await expect(houses.last()).toBeEnabled()
  const skip = page.getByRole('button', { name: 'Skip turn' })
  await skip.click()
  await expect(cart).toBeDisabled()
  await expect(cart).toContainText('Used')
  await skip.click()
  await skip.click()
  await skip.click()
  await expect(skip).toBeDisabled()
  await expect(page.locator('.score.player-0')).toContainText('0 skips · 2 cards')

  await double.click()
  await place(page, 6).click()
  await site(page, 'Tower').click()
  await expect(page.locator('.activity')).toContainText('Used Double Load.')
  await expect(page.locator('.score.player-0')).toContainText('5 / 12 bricks')
})
