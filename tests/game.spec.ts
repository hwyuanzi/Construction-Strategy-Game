test('completes a mobile Standard Match with reduced motion', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'How to play' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'New match' }).click()
  await page.getByRole('button', { name: /Standard Match/ }).click()
  await page.getByRole('spinbutton', { name: 'City seed' }).fill('27')
  await page.getByRole('button', { name: 'Start match' }).click()
  expect(await page.locator('body').evaluate(body => body.scrollWidth)).toBeLessThanOrEqual(390)
  for (let week = 1; week <= 12; week++) {
    const planning = page.getByRole('heading', { name: 'Choose a project' })
    const recap = page.getByRole('heading', { name: `Week ${week} results` })
    await expect(planning.or(recap)).toBeVisible()
    if (await planning.isVisible()) await playWeek(page, true)
    await expect(recap).toBeVisible()
    await page.getByRole('button', { name: week === 12 ? 'See final results' : 'Next week' }).click()
  }
  await expect(page.getByText('After 12 weeks of construction')).toBeVisible()
})
