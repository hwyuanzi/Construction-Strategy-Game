import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function playWeek(page: Page, bid: boolean) {
  await page.getByRole('button', { name: /Continue to bidding|Review crew plan/ }).click()
  const crane = page.getByRole('heading', { name: 'Compete for a crane' })
  if (await crane.isVisible()) {
    if (bid) await page.getByRole('button', { name: /Place bid/ }).first().click()
    else await page.getByRole('button', { name: 'Skip crane this week' }).click()
    await page.getByRole('button', { name: 'Review crew plan' }).click()
  }
  await page.getByRole('button', { name: 'Lock week' }).click()
}

test('plays Quick Match against Greedy from the contested opening to final cash', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'City overview' })).toBeVisible()
  await page.getByRole('button', { name: 'Crestline Co. Starter Commercial' }).click()
  await expect(page.getByText('1/4 shifts')).toBeVisible()
  await page.getByRole('button', { name: 'Close site details' }).click()
  await page.getByRole('button', { name: /House.*payout/ }).click()
  await page.getByRole('button', { name: 'Continue to bidding' }).click()
  await page.getByRole('button', { name: /Place bid/ }).click()
  await page.getByRole('button', { name: 'Increase bid' }).click()
  await page.getByRole('button', { name: 'Review crew plan' }).click()
  await expect(page.getByRole('button', { name: /Push steel frame/ })).toBeVisible()
  await page.getByRole('button', { name: /Prioritize house/ }).click()
  const budget = page.getByRole('button', { name: 'Budget & crew controls' })
  await expect(budget).toHaveAttribute('aria-expanded', 'false')
  await budget.click()
  await expect(page.getByText('Spend if you lose', { exact: true })).toBeVisible()
  await expect(page.getByRole('spinbutton', { name: 'Starter House shifts' })).toHaveValue('1')
  await budget.click()
  await page.getByRole('button', { name: 'Lock week' }).click()
  await expect(page.getByRole('heading', { name: 'Week 1 results' })).toBeVisible()
  await expect(page.getByText('Won crane', { exact: true })).toBeVisible()
  await expect(page.getByText('Crestline Co. picked up the house permit.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Crestline Co. Starter House' })).toHaveClass(/complete-pin/)
  for (let week = 2; week <= 8; week++) {
    await page.getByRole('button', { name: 'Next week' }).click()
    const planning = page.getByRole('heading', { name: 'Choose a project' })
    const recap = page.getByRole('heading', { name: `Week ${week} results` })
    await expect(planning.or(recap)).toBeVisible()
    if (await planning.isVisible()) await playWeek(page, true)
    await expect(recap).toBeVisible()
  }
  await page.getByRole('button', { name: 'See final results' }).click()
  await expect(page.getByRole('heading', { name: /wins|tie/ })).toBeVisible()
  await expect(page.getByText('After 8 weeks of construction')).toBeVisible()
  expect(errors).toEqual([])
})

